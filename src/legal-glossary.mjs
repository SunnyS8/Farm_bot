const normalize = text => text.normalize('NFKC').toLowerCase().replaceAll('ё', 'е')
  .replace(/[‐‑‒–—−]/g, '-').replace(/\s+/g, ' ').trim();

const SPS = `Общая справка (вне локального сборника).

СПС — это справочная правовая система: электронная база нормативных актов, судебной практики, разъяснений, форм документов и аналитических материалов.

Примеры СПС: «КонсультантПлюс» и «ГАРАНТ». Они помогают находить редакции документов, связи между актами и профессиональные комментарии.

Важно различать:
• официальный текст и официальное опубликование нормативного акта;
• представление документа, редакцию и комментарии внутри СПС.

Перед юридически значимым применением проверяют реквизиты, дату редакции, статус документа и официальный первоисточник.

Справочно.`;

export function glossaryAnswer(question) {
  const q = normalize(question);
  if (/(?:что\s+такое|что\s+значит|расшифруй\p{L}*)\s+(?:аббревиатур\p{L}*\s+)?[«"]?спс[»"]?[?!.]*$/u.test(q) ||
      /(?:^|\s)спс\s*-\s*это/u.test(q)) return SPS;
  return null;
}

export function isDefinitionQuestion(question) {
  const q = normalize(question);
  return q.length <= 500 &&
    /^(?:а\s+)?(?:что\s+такое|что\s+значит|что\s+означает|расшифруй|объясни\s+термин)(?:\s|$)/u.test(q);
}
